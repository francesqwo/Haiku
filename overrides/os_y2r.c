/* os: native nn::y2r, see zakuro-core/src/pcos/y2r.rs.
 *
 * The movie player (mw::mo, Mobiclip) converts each decoded YUV frame to RGB
 * with the y2r hardware through nn::y2r::CTR::detail::Y2r, one IPC request
 * per setting and one to start. These overrides send each straight to the
 * native converter, through the bridge overrides/os_fs.c defines.
 */
#include "overrides.h"

typedef int (*OsNativeHook)(Context *ctx, uint32_t op);
extern OsNativeHook os_native_hook;

#define OS_NATIVE(op, address) do { \
    if (os_native_hook && os_native_hook(ctx, (op))) RETURN_TO(ctx->r[14]); \
    CALL(RECOMP_ORIGINAL(address)); \
} while (0)

/* call numbers, the same as pcos::y2r::op */
enum {
    OS_Y2R_SET_INPUT_FORMAT = 0x300,
    OS_Y2R_SET_OUTPUT_FORMAT,
    OS_Y2R_SET_ROTATION,
    OS_Y2R_SET_BLOCK_ALIGNMENT,
    OS_Y2R_SET_TRANSFER_END_INTERRUPT,
    OS_Y2R_GET_TRANSFER_END_EVENT,
    OS_Y2R_SET_SENDING_Y,
    OS_Y2R_SET_SENDING_U,
    OS_Y2R_SET_SENDING_V,
    OS_Y2R_SET_RECEIVING,
    OS_Y2R_SET_INPUT_LINE_WIDTH,
    OS_Y2R_SET_INPUT_LINES,
    OS_Y2R_SET_STANDARD_COEFFICIENT,
    OS_Y2R_SET_ALPHA,
    OS_Y2R_START_CONVERSION,
    OS_Y2R_STOP_CONVERSION,
    OS_Y2R_IS_BUSY_CONVERSION,
    OS_Y2R_DRIVER_INITIALIZE,
    OS_Y2R_DRIVER_FINALIZE,
};

